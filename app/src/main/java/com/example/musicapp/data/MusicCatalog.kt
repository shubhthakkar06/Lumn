    fun getPlaylistSongs(playlistId: String, title: String): List<SongInfo> {
        val lowerId = playlistId.lowercase()
        val lowerTitle = title.lowercase()
        return when {
            lowerId.contains("liked") || lowerTitle.contains("liked") -> emptyList()
            lowerId.contains("coldplay") || lowerTitle.contains("coldplay") -> getArtistData("Coldplay").topTracks
            lowerId.contains("arijit") || lowerTitle.contains("arijit") -> getArtistData("Arijit Singh").topTracks
            lowerId.contains("pritam") || lowerTitle.contains("pritam") -> getArtistData("Pritam").topTracks
